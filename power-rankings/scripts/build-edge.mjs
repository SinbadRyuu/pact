// Bundles server/ into one ES module for a Supabase Edge Function (Deno).
//   node scripts/build-edge.mjs   → supabase/functions/rankings/rankings-api.js
import { build } from "esbuild";
await build({
  entryPoints: ["server/index.ts"],
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2022",
  outfile: "supabase/functions/rankings/rankings-api.js",
  banner: { js: "// Generated by power-rankings/scripts/build-edge.mjs. Don't edit; edit power-rankings/server/ and rebuild." },
  logLevel: "info",
});

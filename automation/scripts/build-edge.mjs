// Bundles server/ into one ES module for a Supabase Edge Function (Deno).
//   node scripts/build-edge.mjs   → supabase/functions/automation/automation-api.js
// Stripe is left as an npm: import, which Deno resolves itself.
import { build } from "esbuild";
await build({
  entryPoints: ["server/index.ts"],
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2022",
  outfile: "supabase/functions/automation/automation-api.js",
  external: ["stripe"],
  plugins: [{ name: "npm-stripe", setup(b) { b.onResolve({ filter: /^stripe$/ }, () => ({ path: "npm:stripe@19.3.1", external: true })); } }],
  banner: { js: "// Generated by automation/scripts/build-edge.mjs. Don't edit; edit automation/server/ and rebuild." },
  logLevel: "info",
});
